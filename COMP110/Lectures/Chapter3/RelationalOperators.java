public class RelationalOperators {
    public static void main(String[] args) {
        int radius = 5;
        System.out.println(radius < 0);
        System.out.println(radius <= 0);
        System.out.println(radius > 0);
        System.out.println(radius >= 0);
        System.out.println(radius == 0);
        System.out.println(radius != 0);
    }
}

public class IntegerDivision {
    public static void main(String[] args) {
        System.out.println(5 / 2);
        System.out.println(5 / 2.0);
        System.out.println(-5 / 2);
        double first = 5 / 2;
        double second = 5.0 / 2;
        System.out.println(first);
        System.out.println(second);
    }
}

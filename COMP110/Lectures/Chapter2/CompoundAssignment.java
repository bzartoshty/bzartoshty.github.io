public class CompoundAssignment {
    public static void main(String[] args) {
        int count = 10;
        count += 3;
        System.out.println(count);
        count -= 2;
        System.out.println(count);
        count *= 4;
        System.out.println(count);
        count /= 5;
        System.out.println(count);
        count %= 3;
        System.out.println(count);
    }
}

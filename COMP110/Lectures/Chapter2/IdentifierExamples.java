public class IdentifierExamples {
    public static void main(String[] args) {
        int studentCount = 24;
        double hourlyRate = 18.5;
        char grade = 'A';
        // int 2students = 24;   // cannot start with a digit
        // int class = 1;        // reserved keyword
        // double hourly-rate;   // hyphen is not part of a name
        System.out.println(studentCount);
        System.out.println(hourlyRate);
        System.out.println(grade);
    }
}

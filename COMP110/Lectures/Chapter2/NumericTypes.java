public class NumericTypes {
    public static void main(String[] args) {
        byte smallCount = 100;
        short seats = 300;
        int population = 1_000_000;
        long distance = 3_000_000_000L;
        float temperature = 18.5F;
        double radius = 18.5;
        System.out.println(smallCount + " " + seats);
        System.out.println(population + " " + distance);
        System.out.println(temperature + " " + radius);
    }
}

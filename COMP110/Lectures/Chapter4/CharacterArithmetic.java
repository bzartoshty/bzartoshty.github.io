public class CharacterArithmetic {
    public static void main(String[] args) {
        char letter = 'a';
        System.out.println(letter + 1);
        System.out.println((char) (letter + 1));
        System.out.println('a' + 'b');
        System.out.println("" + 'a' + 'b');
    }
}

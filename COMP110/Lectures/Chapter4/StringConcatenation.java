public class StringConcatenation {
    public static void main(String[] args) {
        String first = "Java";
        String joined = first.concat(" is fun");
        System.out.println(joined);
        System.out.println("Sum: " + 2 + 3);
        System.out.println("Sum: " + (2 + 3));
        System.out.println(first);
    }
}

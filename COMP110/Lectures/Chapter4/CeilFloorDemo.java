public class CeilFloorDemo {
    public static void main(String[] args) {
        System.out.println(Math.ceil(2.3));
        System.out.println(Math.floor(2.3));
        System.out.println(Math.ceil(-2.3));
        System.out.println(Math.floor(-2.3));
        System.out.println((int) -2.3);
    }
}
